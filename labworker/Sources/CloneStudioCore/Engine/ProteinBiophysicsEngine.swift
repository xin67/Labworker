public enum ProteinSecondaryType: String, Codable, Sendable {
    case helix = "H"
    case sheet = "E"
    case coil  = "C"
    
    public var title: String {
        switch self {
        case .helix: return "α-螺旋 (Helix)"
        case .sheet: return "β-折叠 (Sheet)"
        case .coil:  return "无规卷曲 (Coil)"
        }
    }
}


import Foundation

// MARK: - qPCR 主流仪器原厂导出表解析 + RDML 双向读写 + MIQE 合规性自检引擎

public enum QPCRInstrumentFormat: String, CaseIterable, Codable, Sendable {
    case quantStudio = "Thermo QuantStudio / StepOne"
    case cfxMaestro = "Bio-Rad CFX Maestro"
    case lightCycler480 = "Roche LightCycler 480"
    case mxPro = "Agilent MxPro / AriaMx"
    case rdml = "RDML v1.3 标准"
    case genericCSV = "通用 CSV / TSV"

    public var shortTitle: String {
        switch self {
        case .quantStudio:    return "QuantStudio"
        case .cfxMaestro:     return "CFX Maestro"
        case .lightCycler480: return "LightCycler 480"
        case .mxPro:          return "MxPro / AriaMx"
        case .rdml:           return "RDML"
        case .genericCSV:     return "通用表格"
        }
    }
}

public struct QPCRImportResult: Sendable {
    public let format: QPCRInstrumentFormat
    public let wells: [QPCRWellRecord]
    public let skippedHeaderLines: Int
    public let metadataSummary: String
}

public enum MIQEStatus: String, Codable, Sendable {
    case pass = "合规"
    case warning = "建议完善"
    case fail = "不合规"
}

public struct MIQEChecklistItem: Identifiable, Codable, Sendable, Equatable {
    public let id: String
    public let itemNumber: Int
    public let title: String
    public let status: MIQEStatus
    public let evidence: String
}

public struct MIQEComplianceReport: Sendable, Equatable {
    public let items: [MIQEChecklistItem]
    public let passCount: Int
    public let warningCount: Int
    public let failCount: Int
    public let detectedFormat: String

    public func exportMarkdownChecklist() -> String {
        var lines = [
            "# qPCR MIQE 合规性自检清单 (Generated by Labworker)",
            "- 检测数据来源: \(detectedFormat)",
            "- 总览: \(passCount) 项合规 · \(warningCount) 项建议完善 · \(failCount) 项不合规",
            ""
        ]
        for item in items {
            let icon = item.status == .pass ? "[x]" : (item.status == .warning ? "[~]" : "[ ]")
            lines.append("- \(icon) **\(item.itemNumber). \(item.title)**（\(item.status.rawValue)）：\(item.evidence)")
        }
        return lines.joined(separator: "\n") + "\n"
    }
}

public enum QPCRInstrumentAndRDMLEngine {

    // MARK: - 1. 多仪器原厂导出表自动嗅探与跳过前导头解析

    public static func parseRawExport(_ rawText: String, defaultTargetName: String = "Target1") -> QPCRImportResult {
        let trimmedStart = rawText.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmedStart.hasPrefix("<rdml") || (trimmedStart.hasPrefix("<?xml") && rawText.contains("<rdml")) {
            if let xmlRes = try? parseRDMLXML(rawText) {
                return xmlRes
            }
        }

        let cleaned = rawText
            .replacingOccurrences(of: "\u{FEFF}", with: "")
            .replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
        let allLines = cleaned.components(separatedBy: "\n")

        // 定位真实表头行：在前 60 行内寻找同时包含孔位/样品词根与 Ct/Cq/Cp 列的分隔符行
        var headerLineIdx: Int? = nil
        var detectedDelimiter: Character = ","
        let maxProbe = min(60, allLines.count)

        let ctKeywords: Set<String> = [
            "ct", "cq", "cp", "c_t", "c\u{0442}", "ct value", "cq value", "ct mean",
            "ct (dr)", "cq (δr)", "cq (dr)", "ct (δr)", "ct值"
        ]
        let locatorKeywords: Set<String> = [
            "well", "well position", "pos", "position", "sample", "sample name", "samplename",
            "name", "well name", "target", "target name", "gene", "孔位", "反应孔", "样品", "样本"
        ]

        for idx in 0..<maxProbe {
            let line = allLines[idx].trimmingCharacters(in: .whitespacesAndNewlines)
            if line.isEmpty || line.hasPrefix("#") || line.hasPrefix("*") { continue }
            let delim = PlateLayoutEngine.detectDelimiter(in: line)
            let cols = PlateLayoutEngine.splitDelimitedLine(line, delimiter: delim)
                .map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }
            guard cols.count >= 3 else { continue }
            let hasCt = cols.contains { ctKeywords.contains($0) || $0.hasPrefix("ct (") || $0.hasPrefix("cq (") }
            let hasLocator = cols.contains { locatorKeywords.contains($0) }
            if hasCt && hasLocator {
                headerLineIdx = idx
                detectedDelimiter = delim
                break
            }
        }

        // 若无完整匹配，降级为首个非空非 `#` 行的通用解析
        let startIdx: Int
        if let hIdx = headerLineIdx {
            startIdx = hIdx
        } else {
            startIdx = allLines.firstIndex {
                let t = $0.trimmingCharacters(in: .whitespacesAndNewlines)
                return !t.isEmpty && !t.hasPrefix("#")
            } ?? 0
            if startIdx < allLines.count {
                detectedDelimiter = PlateLayoutEngine.detectDelimiter(in: allLines[startIdx])
            }
        }

        guard startIdx + 1 < allLines.count else {
            return QPCRImportResult(format: .genericCSV, wells: [], skippedHeaderLines: startIdx, metadataSummary: "")
        }

        let metaLines = allLines[0..<startIdx]
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
        let metaText = metaLines.joined(separator: " | ")

        let rawHeaders = PlateLayoutEngine.splitDelimitedLine(allLines[startIdx], delimiter: detectedDelimiter)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }

        let format = inferInstrumentFormat(headers: rawHeaders, metaText: metaText)

        func findCol(_ candidates: Set<String>) -> Int? {
            rawHeaders.firstIndex { candidates.contains($0) }
        }
        func findColPrefix(_ prefixes: [String]) -> Int? {
            rawHeaders.firstIndex { col in prefixes.contains { col.hasPrefix($0) } }
        }

        let wellCol = findCol(["well", "well position", "pos", "position", "孔位", "反应孔"]) ?? 0
        let sampleCol = findCol(["sample", "sample name", "samplename", "sample_name", "name", "well name", "样品", "样本"]) ?? 1
        let targetCol = findCol(["target", "target name", "targetname", "gene", "detector", "目的基因", "基因", "靶标"])
        let fluorCol = findCol(["fluor", "reporter", "dye", "channel"])
        let ctCol = findCol(["ct", "cq", "cp", "c_t", "c\u{0442}", "ct value", "cq value", "ct mean", "ct值"])
            ?? findColPrefix(["ct (", "cq (", "cp ("])
            ?? 3
        let groupCol = findCol(["group", "condition", "treatment", "biological group", "分组", "组别"])
        let taskCol = findCol(["task", "content", "type", "well_type", "well type", "role", "status", "类型", "孔类型", "任务"])
        let tmCol = findCol(["tm", "tm1", "tm1 (c)", "tm value", "melt", "melting", "melt temperature", "熔解温度", "tm值"])
            ?? findColPrefix(["tm1"])
        let repCol = findCol(["replicate", "rep", "replicates", "复孔"])
        let qtyCol = findCol(["quantity", "qty", "conc", "concentration", "starting quantity (sq)", "quantity (copies)", "standard", "浓度", "标准品浓度"])
        let effCol = findCol(["efficiency", "eff", "扩增效率"])

        var records: [QPCRWellRecord] = []
        for idx in (startIdx + 1)..<allLines.count {
            let line = allLines[idx].trimmingCharacters(in: .whitespacesAndNewlines)
            if line.isEmpty || line.hasPrefix("#") || line.hasPrefix("[") { continue }
            let cells = PlateLayoutEngine.splitDelimitedLine(line, delimiter: detectedDelimiter)
            func cellAt(_ col: Int?) -> String {
                guard let c = col, c >= 0, c < cells.count else { return "" }
                return cells[c].trimmingCharacters(in: .whitespacesAndNewlines)
            }
            let well = cellAt(wellCol)
            let sample = cellAt(sampleCol)
            var target = cellAt(targetCol)
            if target.isEmpty {
                let fl = cellAt(fluorCol)
                target = fl.isEmpty ? defaultTargetName : fl
            }
            if sample.isEmpty && target.isEmpty { continue }

            let ctRaw = cellAt(ctCol).lowercased()
            let ctVal: Double? = (ctRaw.isEmpty || ctRaw == "undetermined" || ctRaw == "no ct" || ctRaw == "n/a" || ctRaw == "na" || ctRaw == "nan" || ctRaw == "-")
                ? nil
                : Double(ctRaw.replacingOccurrences(of: ",", with: ""))

            let group = cellAt(groupCol)
            let taskRaw = cellAt(taskCol)
            let tmVal = parseFlexibleDouble(cellAt(tmCol))
            let rep = Int(cellAt(repCol))
            let qty = parseFlexibleDouble(cellAt(qtyCol))
            let eff = parseFlexibleDouble(cellAt(effCol))
            let normalizedTask = normalizeInstrumentTask(taskRaw)
            let wellType = QPCRWellType.infer(sample: sample, group: group, taskRaw: normalizedTask, quantity: qty)

            records.append(
                QPCRWellRecord(
                    id: "row_\(idx)_\(well)",
                    row: records.count,
                    well: well.isEmpty ? "W\(records.count + 1)" : well,
                    sample: sample,
                    target: target,
                    group: group,
                    wellType: wellType,
                    replicate: rep,
                    ct: ctVal,
                    tm: tmVal,
                    efficiency: eff,
                    quantity: qty,
                    include: true
                )
            )
        }

        return QPCRImportResult(
            format: format,
            wells: records,
            skippedHeaderLines: startIdx,
            metadataSummary: metaText
        )
    }

    private static func inferInstrumentFormat(headers: [String], metaText: String) -> QPCRInstrumentFormat {
        let lowerMeta = metaText.lowercased()
        let hSet = Set(headers)
        if lowerMeta.contains("quantstudio") || lowerMeta.contains("stepone") || hSet.contains("well position") || hSet.contains("target name") || hSet.contains("c\u{0442}") {
            return .quantStudio
        }
        if lowerMeta.contains("cfx") || lowerMeta.contains("bio-rad") || (hSet.contains("fluor") && hSet.contains("cq") && hSet.contains("content")) {
            return .cfxMaestro
        }
        if lowerMeta.contains("lightcycler") || lowerMeta.contains("selected filter") || (hSet.contains("pos") && hSet.contains("cp")) {
            return .lightCycler480
        }
        if lowerMeta.contains("mxpro") || lowerMeta.contains("ariamx") || hSet.contains("well type") || headers.contains(where: { $0.hasPrefix("ct (dr)") || $0.hasPrefix("cq (") }) {
            return .mxPro
        }
        return .genericCSV
    }

    private static func normalizeInstrumentTask(_ raw: String) -> String {
        let low = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if low == "unkn" || low == "unknown" || low == "pos ctrl" { return "sample" }
        if low == "std" || low == "standard" { return "standard" }
        if low == "ntc" || low == "neg ctrl" || low == "water" { return "ntc" }
        if low == "nrt" || low == "no rt" || low == "no-rt" { return "no-rt" }
        return raw
    }

    private static func parseFlexibleDouble(_ raw: String) -> Double? {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.lowercased() != "none", trimmed.lowercased() != "na", trimmed != "-" else { return nil }
        return Double(trimmed)
    }

    // MARK: - 2. RDML (.rdml ZIP / XML) 双向读写（零第三方依赖）

    public static func parseRDMLData(_ data: Data, fileName: String = "experiment.rdml") throws -> QPCRImportResult {
        // 检查是否为 ZIP 归档 (魔数 PK\x03\x04)
        if data.count >= 4, data[0] == 0x50, data[1] == 0x4B, data[2] == 0x03, data[3] == 0x04 {
            let tmpDir = FileManager.default.temporaryDirectory.appendingPathComponent("labworker_rdml_\(UUID().uuidString)", isDirectory: true)
            try FileManager.default.createDirectory(at: tmpDir, withIntermediateDirectories: true)
            defer { try? FileManager.default.removeItem(at: tmpDir) }

            let archiveURL = tmpDir.appendingPathComponent("input.rdml")
            try data.write(to: archiveURL)

            let listing = try runSystemTool(executable: "/usr/bin/unzip", arguments: ["-Z1", archiveURL.path])
            let entries = listing.components(separatedBy: .newlines).map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
            let xmlEntry = entries.first(where: { $0.lowercased() == "rdml_data.xml" }) ?? entries.first(where: { $0.lowercased().hasSuffix(".xml") })
            guard let entry = xmlEntry else {
                throw NSError(domain: "LabworkerRDML", code: 1, userInfo: [NSLocalizedDescriptionKey: "RDML 压缩包内未找到 XML 数据文件。"])
            }
            let xmlText = try runSystemTool(executable: "/usr/bin/unzip", arguments: ["-p", archiveURL.path, entry])
            return try parseRDMLXML(xmlText)
        }

        guard let xmlText = String(data: data, encoding: .utf8) ?? String(data: data, encoding: .ascii) else {
            throw NSError(domain: "LabworkerRDML", code: 2, userInfo: [NSLocalizedDescriptionKey: "无法以 UTF-8/ASCII 解码 RDML XML 文件。"])
        }
        return try parseRDMLXML(xmlText)
    }

    public static func parseRDMLXML(_ xmlText: String) throws -> QPCRImportResult {
        guard let xmlData = xmlText.data(using: .utf8) else {
            throw NSError(domain: "LabworkerRDML", code: 3, userInfo: [NSLocalizedDescriptionKey: "XML 文本编码无效。"])
        }
        let delegate = RDMLSAXParserDelegate()
        let parser = XMLParser(data: xmlData)
        parser.delegate = delegate
        guard parser.parse() else {
            throw parser.parserError ?? NSError(domain: "LabworkerRDML", code: 4, userInfo: [NSLocalizedDescriptionKey: "RDML XML 语法解析失败。"])
        }

        var records: [QPCRWellRecord] = []
        for (idx, react) in delegate.reacts.enumerated() {
            let sampleID = react.sampleID
            let sMeta = delegate.samples[sampleID]
            let wellName = formatRDMLWellLabel(react.id, fallbackIndex: idx + 1)
            let wType: QPCRWellType = {
                switch (sMeta?.type ?? "").lowercased() {
                case "ntc": return .ntc
                case "nrt": return .noRT
                case "std": return .standard
                default:
                    if sMeta?.quantity != nil { return .standard }
                    return QPCRWellType.infer(sample: sampleID, taskRaw: sMeta?.type ?? "", quantity: sMeta?.quantity)
                }
            }()

            for d in react.dataEntries {
                records.append(
                    QPCRWellRecord(
                        id: "rdml_\(idx)_\(d.tarID)",
                        row: records.count,
                        well: wellName,
                        sample: sampleID,
                        target: d.tarID,
                        group: sMeta?.group ?? "",
                        wellType: wType,
                        replicate: nil,
                        ct: d.cq,
                        tm: d.tm,
                        efficiency: nil,
                        quantity: sMeta?.quantity,
                        include: !(d.excl?.lowercased() == "true")
                    )
                )
            }
        }

        return QPCRImportResult(
            format: .rdml,
            wells: records,
            skippedHeaderLines: 0,
            metadataSummary: "RDML v\(delegate.version) · \(delegate.experimentID) (\(records.count) 反应记录)"
        )
    }

    public static func exportRDMLXML(
        wells: [QPCRWellRecord],
        settings: QPCRSettings,
        experimentName: String = "Labworker_Experiment"
    ) -> String {
        func esc(_ s: String) -> String {
            s.replacingOccurrences(of: "&", with: "&amp;")
                .replacingOccurrences(of: "<", with: "&lt;")
                .replacingOccurrences(of: ">", with: "&gt;")
                .replacingOccurrences(of: "\"", with: "&quot;")
        }

        var samplesOrdered: [(id: String, type: String, qty: Double?)] = []
        var seenSamples = Set<String>()
        var targetsOrdered: [(id: String, type: String)] = []
        var seenTargets = Set<String>()
        let refKeys = Set(settings.referenceTargets.map { QPCRAnalysisEngine.normKey($0) })

        for w in wells {
            if !seenSamples.contains(w.sample) {
                seenSamples.insert(w.sample)
                let sType: String = {
                    switch w.wellType {
                    case .ntc: return "ntc"
                    case .noRT: return "nrt"
                    case .standard: return "std"
                    case .sample: return "unkn"
                    }
                }()
                samplesOrdered.append((w.sample, sType, w.quantity))
            }
            if !seenTargets.contains(w.target) {
                seenTargets.insert(w.target)
                let isRef = refKeys.contains(QPCRAnalysisEngine.normKey(w.target))
                targetsOrdered.append((w.target, isRef ? "ref" : "toi"))
            }
        }

        var lines: [String] = [
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
            "<rdml xmlns=\"http://www.rdml.org\" version=\"1.3\">",
            "  <documentation id=\"labworker_meta\"><text>Exported by Labworker QPCRInstrumentAndRDMLEngine</text></documentation>"
        ]
        for s in samplesOrdered {
            lines.append("  <sample id=\"\(esc(s.id))\">")
            lines.append("    <type>\(s.type)</type>")
            if let q = s.qty {
                lines.append("    <quantity><value>\(q)</value><unit>cop</unit></quantity>")
            }
            lines.append("  </sample>")
        }
        for t in targetsOrdered {
            lines.append("  <target id=\"\(esc(t.id))\">")
            lines.append("    <type>\(t.type)</type>")
            lines.append("  </target>")
        }

        lines.append("  <experiment id=\"\(esc(experimentName))\">")
        lines.append("    <run id=\"run_1\">")
        lines.append("      <pcrFormat><rows>8</rows><columns>12</columns><rowLabel>ABC</rowLabel><columnLabel>123</columnLabel></pcrFormat>")
        for (idx, w) in wells.enumerated() {
            let reactID = wellLabelToRDMLReactID(w.well, fallback: idx + 1)
            lines.append("      <react id=\"\(esc(reactID))\">")
            lines.append("        <sample id=\"\(esc(w.sample))\"/>")
            lines.append("        <data>")
            lines.append("          <tar id=\"\(esc(w.target))\"/>")
            if let cq = w.ct {
                lines.append("          <cq>\(String(format: "%.4f", cq))</cq>")
            }
            if let tm = w.tm {
                lines.append("          <tm>\(String(format: "%.2f", tm))</tm>")
            }
            if !w.include {
                lines.append("          <excl>true</excl>")
            }
            lines.append("        </data>")
            lines.append("      </react>")
        }
        lines.append("    </run>")
        lines.append("  </experiment>")
        lines.append("</rdml>")
        return lines.joined(separator: "\n") + "\n"
    }

    public static func writeRDMLArchive(
        wells: [QPCRWellRecord],
        settings: QPCRSettings,
        experimentName: String = "Labworker_Experiment",
        to destinationURL: URL
    ) throws {
        let xml = exportRDMLXML(wells: wells, settings: settings, experimentName: experimentName)
        if destinationURL.pathExtension.lowercased() == "xml" {
            try xml.write(to: destinationURL, atomically: true, encoding: .utf8)
            return
        }

        let tmpDir = FileManager.default.temporaryDirectory.appendingPathComponent("labworker_rdml_out_\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: tmpDir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tmpDir) }

        let xmlURL = tmpDir.appendingPathComponent("rdml_data.xml")
        try xml.write(to: xmlURL, atomically: true, encoding: .utf8)
        let zipOut = tmpDir.appendingPathComponent("out.rdml")
        _ = try runSystemTool(executable: "/usr/bin/zip", arguments: ["-j", "-q", zipOut.path, xmlURL.path])
        let zipData = try Data(contentsOf: zipOut)
        try zipData.write(to: destinationURL, options: .atomic)
    }

    // MARK: - 3. MIQE 合规性自检清单评估

    public static func evaluateMIQECompliance(
        wells: [QPCRWellRecord],
        settings: QPCRSettings,
        qc: [String: QPCRWellQCResult],
        ddctOut: QPCRDdctAnalysisOut,
        stdOut: QPCRStandardAnalysisOut,
        detectedFormat: QPCRInstrumentFormat
    ) -> MIQEComplianceReport {
        var items: [MIQEChecklistItem] = []

        // 1. 生物学重复充分性 (至少 n_bio >= 3)
        let experimentalGroups = ddctOut.groupResults.filter { !$0.isControl }
        let minBio = experimentalGroups.map(\.nBiological).min() ?? 0
        let bioStatus: MIQEStatus = experimentalGroups.isEmpty ? .fail : (minBio >= 3 ? .pass : .warning)
        items.append(MIQEChecklistItem(
            id: "bio_reps",
            itemNumber: 1,
            title: "生物学重复充分性 (MIQE Essential)",
            status: bioStatus,
            evidence: experimentalGroups.isEmpty
                ? "未检测到有效处理组数据。"
                : (minBio >= 3 ? "所有处理组生物学重复 n ≥ \(minBio)（满足统计学 Welch 检验最低推荐 n ≥ 3）。" : "部分组生物学重复仅 n = \(minBio)（低于 3，无法进行稳健群体显著性检验）。")
        ))

        // 2. 技术复孔离散度 (SD <= threshold)
        let highSdCount = qc.values.filter { $0.flags.contains(.replicateSd) }.count
        items.append(MIQEChecklistItem(
            id: "tech_sd",
            itemNumber: 2,
            title: "技术复孔一致性与 SD 质控",
            status: highSdCount == 0 ? .pass : .warning,
            evidence: highSdCount == 0
                ? String(format: "全部反应复孔 Ct 标准差均 ≤ %.2f。", settings.sdLimit)
                : String(format: "发现 %d 个反应孔超出复孔 SD 上限 (%.2f)，请核查加样一致性或勾选剔除离群孔。", highSdCount, settings.sdLimit)
        ))

        // 3. 内参基因数量与几何平均策略
        let refCount = ddctOut.references.count
        let refStatus: MIQEStatus = refCount >= 2 ? .pass : (refCount == 1 ? .warning : .fail)
        items.append(MIQEChecklistItem(
            id: "ref_genes",
            itemNumber: 3,
            title: "内参基因归一化 (Vandesompele 策略)",
            status: refStatus,
            evidence: refCount >= 2
                ? "已选用 \(refCount) 个内参 (\(ddctOut.references.joined(separator: ", "))) 执行几何平均归一化。"
                : (refCount == 1 ? "当前仅使用单个内参 (\(ddctOut.references.first ?? ""))；MIQE 建议条件允许时使用 ≥2 个稳定内参几何平均。" : "未配置有效内参基因。")
        ))

        // 4. 扩增效率与标准曲线 R²
        let stdFits = stdOut.fits
        let effItem: MIQEChecklistItem = {
            if stdFits.isEmpty {
                return MIQEChecklistItem(
                    id: "efficiency",
                    itemNumber: 4,
                    title: "引物扩增效率 (90%–110%) 与标准曲线 R²",
                    status: .warning,
                    evidence: "当前数据集未包含稀释标准品孔；假定默认扩增效率为 \(String(format: "%.0f%%", settings.defaultEfficiencyPct))。"
                )
            }
            let good = stdFits.allSatisfy { f in
                guard let eff = f.efficiencyPct, let r2 = f.r2 else { return false }
                return eff >= 90.0 && eff <= 110.0 && r2 >= 0.98
            }
            let summary = stdFits.compactMap { f -> String? in
                guard let eff = f.efficiencyPct, let r2 = f.r2 else { return nil }
                return "\(f.target): E=\(String(format: "%.1f%%", eff)), R²=\(String(format: "%.4f", r2))"
            }.joined(separator: "; ")
            return MIQEChecklistItem(
                id: "efficiency",
                itemNumber: 4,
                title: "引物扩增效率 (90%–110%) 与标准曲线 R²",
                status: good ? .pass : .warning,
                evidence: summary.isEmpty ? "标准品拟合未完成。" : summary
            )
        }()
        items.append(effItem)

        // 5. NTC 无模板阴性对照
        let ntcWells = wells.filter { $0.wellType == .ntc }
        let ntcDirty = qc.values.filter { $0.flags.contains(.ntcAmplified) }.count
        items.append(MIQEChecklistItem(
            id: "ntc",
            itemNumber: 5,
            title: "NTC 无模板阴性对照检测",
            status: ntcWells.isEmpty ? .warning : (ntcDirty == 0 ? .pass : .fail),
            evidence: ntcWells.isEmpty
                ? "当前表未包含 NTC 孔（MIQE 建议每板为各引物设置 NTC 排查引物二聚体或气溶胶污染）。"
                : (ntcDirty == 0 ? "包含 \(ntcWells.count) 个 NTC 孔，均未见阈值前异常起峰。" : "警告：\(ntcDirty) 个 NTC 孔出现起峰（Ct < \(settings.ntcCtThreshold)），存在模板或引物二聚体污染风险！")
        ))

        // 6. no-RT 对照排查 gDNA 残留
        let noRTWells = wells.filter { $0.wellType == .noRT }
        let noRTDirty = qc.values.filter { $0.flags.contains(.noRTAmplified) }.count
        items.append(MIQEChecklistItem(
            id: "no_rt",
            itemNumber: 6,
            title: "no-RT 无逆转录对照 (gDNA 污染评估)",
            status: noRTWells.isEmpty ? .warning : (noRTDirty == 0 ? .pass : .fail),
            evidence: noRTWells.isEmpty
                ? "当前表未包含 no-RT 对照孔；若引物不跨外显子接头，建议补充 no-RT 对照。"
                : (noRTDirty == 0 ? "包含 \(noRTWells.count) 个 no-RT 孔，ΔCt 满足基因组污染安全阈值。" : "警告：\(noRTDirty) 个 no-RT 孔与 cDNA 样品 ΔCt < \(settings.noRTDeltaCtThreshold)，提示存在 gDNA 残留。")
        ))

        // 7. 熔解曲线 Tm 特异性校验
        let tmWells = wells.filter { $0.tm != nil }
        let tmBad = qc.values.filter { $0.flags.contains(.meltOutlier) }.count
        items.append(MIQEChecklistItem(
            id: "melt_tm",
            itemNumber: 7,
            title: "熔解曲线 Tm 特异性验证",
            status: tmWells.isEmpty ? .warning : (tmBad == 0 ? .pass : .fail),
            evidence: tmWells.isEmpty
                ? "导入表未含熔解温度 (Tm) 列，跳过特异性偏离筛查。"
                : (tmBad == 0 ? "已验证 \(tmWells.count) 个反应孔 Tm 均在靶标中位峰 ±\(settings.meltTolerance)℃ 内。" : "检出 \(tmBad) 个孔 Tm 偏离主峰，已自动标记避免非特异产物纳入定量。")
        ))

        // 8. 多重比较校正与可复现溯源
        items.append(MIQEChecklistItem(
            id: "stats_provenance",
            itemNumber: 8,
            title: "多重假设检验校正与溯源记录",
            status: settings.multipleComparison == .holm ? .pass : .warning,
            evidence: settings.multipleComparison == .holm
                ? "已启用 Holm–Bonferroni 家族内多重检验校正，导出时自动伴生 AnalysisRun v2 (SHA-256) 溯源 JSON。"
                : "当前使用未校正 Raw p 值；建议开启 Holm–Bonferroni 校正。"
        ))

        let pCnt = items.filter { $0.status == .pass }.count
        let wCnt = items.filter { $0.status == .warning }.count
        let fCnt = items.filter { $0.status == .fail }.count

        return MIQEComplianceReport(
            items: items,
            passCount: pCnt,
            warningCount: wCnt,
            failCount: fCnt,
            detectedFormat: detectedFormat.rawValue
        )
    }

    // MARK: - 内部系统 ZIP 工具与 XML 解析辅助 (DispatchGroup 防管道死锁)

    private static func runSystemTool(executable: String, arguments: [String]) throws -> String {
        let proc = Process()
        proc.executableURL = URL(fileURLWithPath: executable)
        proc.arguments = arguments

        let outPipe = Pipe()
        let errPipe = Pipe()
        proc.standardOutput = outPipe
        proc.standardError = errPipe

        var outData = Data()
        var errData = Data()
        let group = DispatchGroup()

        group.enter()
        DispatchQueue.global(qos: .userInitiated).async {
            outData = outPipe.fileHandleForReading.readDataToEndOfFile()
            group.leave()
        }
        group.enter()
        DispatchQueue.global(qos: .userInitiated).async {
            errData = errPipe.fileHandleForReading.readDataToEndOfFile()
            group.leave()
        }

        try proc.run()
        group.wait()
        proc.waitUntilExit()

        if proc.terminationStatus != 0 {
            let errText = String(data: errData, encoding: .utf8) ?? ""
            throw NSError(domain: "LabworkerRDML", code: Int(proc.terminationStatus), userInfo: [NSLocalizedDescriptionKey: "系统归档工具执行失败：\(errText)"])
        }
        return String(data: outData, encoding: .utf8) ?? ""
    }

    private static func formatRDMLWellLabel(_ rawID: String, fallbackIndex: Int) -> String {
        let t = rawID.trimmingCharacters(in: .whitespacesAndNewlines)
        if let num = Int(t), num >= 1 && num <= 96 {
            let row = (num - 1) / 12
            let col = (num - 1) % 12 + 1
            let rowChar = Character(UnicodeScalar(65 + row)!)
            return "\(rowChar)\(col)"
        }
        if !t.isEmpty { return t }
        return "W\(fallbackIndex)"
    }

    private static func wellLabelToRDMLReactID(_ well: String, fallback: Int) -> String {
        let up = well.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        if let first = up.unicodeScalars.first, first.value >= 65 && first.value <= 80,
           let col = Int(up.dropFirst()), col >= 1 && col <= 24 {
            let row = Int(first.value) - 65
            let cols = col > 12 ? 24 : 12
            return "\(row * cols + col)"
        }
        return "\(fallback)"
    }

    private final class RDMLSAXParserDelegate: NSObject, XMLParserDelegate {
        struct SampleMeta {
            var type: String = "unkn"
            var group: String = ""
            var quantity: Double? = nil
        }
        struct ReactData {
            var tarID: String = ""
            var cq: Double? = nil
            var tm: Double? = nil
            var excl: String? = nil
        }
        struct ReactEntry {
            var id: String = ""
            var sampleID: String = ""
            var dataEntries: [ReactData] = []
        }

        var version: String = "1.3"
        var experimentID: String = "RDML_Experiment"
        var samples: [String: SampleMeta] = [:]
        var reacts: [ReactEntry] = []

        private var elementStack: [String] = []
        private var currentText: String = ""
        private var currentSampleID: String? = nil
        private var currentSampleMeta: SampleMeta? = nil
        private var currentReact: ReactEntry? = nil
        private var currentData: ReactData? = nil
        private var insideQuantity: Bool = false

        func parser(_ parser: XMLParser, didStartElement elementName: String, namespaceURI: String?, qualifiedName qName: String?, attributes attributeDict: [String: String] = [:]) {
            let tag = elementName.components(separatedBy: ":").last?.lowercased() ?? elementName.lowercased()
            elementStack.append(tag)
            currentText = ""

            switch tag {
            case "rdml":
                if let v = attributeDict["version"] { version = v }
            case "experiment":
                if let eid = attributeDict["id"] { experimentID = eid }
            case "sample":
                let sid = attributeDict["id"] ?? ""
                if currentReact != nil {
                    currentReact?.sampleID = sid
                } else if !sid.isEmpty {
                    currentSampleID = sid
                    currentSampleMeta = samples[sid] ?? SampleMeta()
                }
            case "quantity":
                insideQuantity = true
            case "react":
                currentReact = ReactEntry(id: attributeDict["id"] ?? "\(reacts.count + 1)", sampleID: "", dataEntries: [])
            case "data":
                currentData = ReactData()
            case "tar":
                if currentData != nil, let tid = attributeDict["id"] {
                    currentData?.tarID = tid
                }
            default:
                break
            }
        }

        func parser(_ parser: XMLParser, foundCharacters string: String) {
            currentText += string
        }

        func parser(_ parser: XMLParser, didEndElement elementName: String, namespaceURI: String?, qualifiedName qName: String?) {
            let tag = elementName.components(separatedBy: ":").last?.lowercased() ?? elementName.lowercased()
            let val = currentText.trimmingCharacters(in: .whitespacesAndNewlines)

            if currentData != nil {
                switch tag {
                case "tar":
                    if currentData?.tarID.isEmpty == true && !val.isEmpty { currentData?.tarID = val }
                case "cq":
                    currentData?.cq = Double(val)
                case "tm":
                    currentData?.tm = Double(val)
                case "excl":
                    currentData?.excl = val
                case "data":
                    if let d = currentData {
                        if !d.tarID.isEmpty {
                            currentReact?.dataEntries.append(d)
                        }
                        currentData = nil
                    }
                default: break
                }
            } else if currentReact != nil && tag == "react" {
                if let r = currentReact {
                    reacts.append(r)
                    currentReact = nil
                }
            } else if currentSampleID != nil {
                switch tag {
                case "type":
                    currentSampleMeta?.type = val
                case "value":
                    if insideQuantity { currentSampleMeta?.quantity = Double(val) }
                case "quantity":
                    insideQuantity = false
                case "sample":
                    if let sid = currentSampleID, let sm = currentSampleMeta {
                        samples[sid] = sm
                    }
                    currentSampleID = nil
                    currentSampleMeta = nil
                default: break
                }
            }

            if !elementStack.isEmpty { _ = elementStack.removeLast() }
            currentText = ""
        }
    }
